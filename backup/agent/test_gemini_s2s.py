"""Live end-to-end test of Gemini Live 3.8 Speech-to-Speech service.
Connects to Google's WebSocket, sends an InputTextRawFrame, and captures
the OutputAudioRawFrames generated by the model.
"""

import asyncio
import os
import time

from pipecat.frames.frames import (
    EndFrame,
    Frame,
    InputTextRawFrame,
    OutputAudioRawFrame,
    StartFrame,
)
from pipecat.pipeline.pipeline import Pipeline
from pipecat.pipeline.worker import PipelineParams, PipelineWorker
from pipecat.processors.aggregators.llm_context import LLMContext
from pipecat.processors.aggregators.llm_response_universal import LLMContextAggregatorPair
from pipecat.processors.frame_processor import FrameDirection, FrameProcessor
from pipecat.services.google.gemini_live.llm import GeminiLiveLLMService
from pipecat.workers.runner import WorkerRunner


class AudioCaptureSink(FrameProcessor):
    def __init__(self):
        super().__init__()
        self.audio_frames = []
        self.first_audio_time = None
        self.start_time = None

    async def process_frame(self, frame: Frame, direction: FrameDirection):
        await super().process_frame(frame, direction)
        if isinstance(frame, OutputAudioRawFrame):
            if self.first_audio_time is None and self.start_time is not None:
                self.first_audio_time = time.time()
            self.audio_frames.append(frame)
        await self.push_frame(frame, direction)


async def main():
    api_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not api_key:
        print("[FAIL] No GEMINI_API_KEY set.")
        return

    print("[1/4] Initializing GeminiLiveLLMService (models/gemini-3.8-live, voice: Aoede)...")
    llm = GeminiLiveLLMService(
        api_key=api_key,
        settings=GeminiLiveLLMService.Settings(model="models/gemini-3.8-live", voice="Aoede"),
        inference_on_context_initialization=False,
    )

    sink = AudioCaptureSink()
    context = LLMContext([])
    user_agg, asst_agg = LLMContextAggregatorPair(context)

    pipeline = Pipeline([user_agg, llm, sink, asst_agg])
    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(audio_in_sample_rate=24000, audio_out_sample_rate=24000),
    )
    runner = WorkerRunner(handle_sigint=False)
    await runner.add_workers(worker)

    runner_task = asyncio.create_task(runner.run())

    print("[2/4] Waiting for pipeline ready...")
    await asyncio.sleep(2.0)

    print("[3/4] Sending InputTextRawFrame('Hello, say test passed') to Gemini...")
    sink.start_time = time.time()
    await worker.queue_frame(InputTextRawFrame("Hello, say test passed"))

    # Wait for audio to be returned
    timeout = 10.0
    start = time.time()
    while time.time() - start < timeout:
        if len(sink.audio_frames) > 10:
            break
        await asyncio.sleep(0.1)

    elapsed = time.time() - start
    ttfb = (sink.first_audio_time - sink.start_time) if sink.first_audio_time else None

    print(f"[4/4] Results after {elapsed:.2f}s:")
    if sink.audio_frames:
        total_bytes = sum(len(f.audio) for f in sink.audio_frames)
        total_secs = total_bytes / (24000 * 2)  # 16-bit mono @ 24k
        print(f"  - Received {len(sink.audio_frames)} OutputAudioRawFrames")
        print(f"  - Total audio duration: {total_secs:.2f}s ({total_bytes} bytes)")
        print(f"  - Time to First Audio Byte (TTFB): {ttfb:.3f}s" if ttfb else "  - TTFB: N/A")
        print("  - Audio Sample Rate:", sink.audio_frames[0].sample_rate)
        print(">>> GEMINI LIVE SPEECH-TO-SPEECH TEST: PASSED <<<")
    else:
        print(">>> GEMINI LIVE SPEECH-TO-SPEECH TEST: FAILED (No audio returned) <<<")

    await runner.stop()
    try:
        await asyncio.wait_for(runner_task, timeout=3.0)
    except Exception:
        runner_task.cancel()


if __name__ == "__main__":
    asyncio.run(main())
